const KEY = 'devops-plan-done';
let done = {};
try {
  done = JSON.parse(localStorage.getItem(KEY) || '{}');
} catch (e) {}

const save = () => {
  try {
    localStorage.setItem(KEY, JSON.stringify(done));
  } catch (e) {}
};

const days = D.days.map(a => ({
  iso: a[0],
  wk: a[1],
  ph: a[2],
  ws: a[3],
  we: a[4],
  wh: a[5],
  m: a[6],
  l: a[7],
  e: a[8],
  dt: new Date(a[0] + 'T00:00:00')
}));

const DN = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];

const fm = m => {
  m = m % 1440;
  const h = Math.floor(m / 60), n = m % 60;
  return (h % 12 || 12) + ':' + String(n).padStart(2, '0') + ' ' + (h < 12 ? 'AM' : 'PM');
};

const fd = d => d.toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' });

const el = (t, c, h) => {
  const e = document.createElement(t);
  if (c) e.className = c;
  if (h != null) e.innerHTML = h;
  return e;
};

const now = new Date();
const todayIso = now.getFullYear() + '-' + String(now.getMonth() + 1).padStart(2, '0') + '-' + String(now.getDate()).padStart(2, '0');

let ti = days.findIndex(d => d.iso === todayIso);
const isToday = ti >= 0;
if (ti < 0) ti = todayIso < days[0].iso ? 0 : days.length - 1;

let sel = ti;

const typeOf = d => {
  const g = d.dt.getDay();
  return g === 6 ? 'Saturday' : g === 0 ? 'Sunday' : 'Weekday';
};

function bar(type, showNow) {
  const b = el('div', 'bar');
  D.tt.filter(r => r[0] === type).forEach(r => {
    const segs = r[2] <= r[1] ? [[r[1], 1440], [0, r[2]]] : [[r[1], r[2]]];
    segs.forEach(s => {
      const x = el('span');
      x.style.width = ((s[1] - s[0]) / 14.4) + '%';
      x.style.background = 'var(' + COL[r[4]] + ')';
      x.title = fm(r[1]) + ' to ' + fm(r[2]) + ': ' + r[3];
      b.appendChild(x);
    });
  });
  if (showNow) {
    const n = el('div', 'now');
    n.style.left = ((now.getHours() * 60 + now.getMinutes()) / 14.4) + '%';
    b.appendChild(n);
  }
  return b;
}

function hero() {
  const d = days[sel], type = typeOf(d), h = document.getElementById('hero');
  h.innerHTML = '';
  h.appendChild(el('h2', 0, DN[d.dt.getDay()] + ', ' + fd(d.dt)));
  h.appendChild(el('div', 0, '<span class="badge">Week ' + d.wk + '</span><span class="badge">' + d.ph + '</span>' + (sel === ti && isToday ? '<span class="badge">Today</span>' : '')));
  h.appendChild(bar(type, isToday && sel === ti));
  
  const tk = el('div', 'ticks', '<span>12 AM</span><span>6 AM</span><span>12 PM</span><span>6 PM</span><span>12 AM</span>');
  h.appendChild(tk);
  h.appendChild(el('div', 'legend', Object.keys(COL).map(k => '<span><b style="background:var(' + COL[k] + ')"></b>' + k + '</span>').join('')));
  
  const s = el('div', 'slots');
  const wd = type === 'Weekday';
  s.appendChild(el('div', 'slot work', '<small>Work</small>' + (wd ? 'Leave home ' + d.ws + ', back by ' + d.we + ' (' + d.wh + ' hours, or 30 minutes less on 7:00 PM days)' : 'Off, at home')));
  
  [
    ['Morning', d.m, '6:00 to 6:30 AM, on the way to work'],
    ['Lunch break', d.l, '12:50 to 1:20 PM'],
    ['Evening', d.e, '8:15 to 10:15 PM']
  ].forEach(x => s.appendChild(el('div', 'slot', '<small>' + x[0] + (wd ? ', ' + x[2] : '') + '</small>' + x[1])));
  
  h.appendChild(s);
  
  const b = el('button', 'btn', done[d.iso] ? 'Mark as not done' : 'Mark day done');
  b.onclick = () => {
    done[d.iso] = !done[d.iso];
    if (!done[d.iso]) delete done[d.iso];
    save();
    render();
  };
  h.appendChild(b);
  
  if (sel !== ti) {
    const t = el('button', 'btn alt', 'Back to today');
    t.onclick = () => {
      sel = ti;
      render();
      scrollTo(0, 0);
    };
    h.appendChild(t);
  }
}

function weeks() {
  const w = document.getElementById('weeks');
  const open = [...w.querySelectorAll('details[open]')].map(x => x.dataset.w);
  w.innerHTML = '';
  
  const g = {};
  days.forEach((d, i) => (g[d.wk] = g[d.wk] || []).push(i));
  
  Object.keys(g).forEach(k => {
    const ix = g[k], f = days[ix[0]], l = days[ix[ix.length - 1]], c = ix.filter(i => done[days[i].iso]).length;
    const de = el('details');
    de.dataset.w = k;
    if (open.includes(k) || (!open.length && ix.includes(ti))) de.open = true;
    
    de.appendChild(el('summary', 0, '<div>Week ' + k + ' <span style="display:block;text-align:left">' + f.ph + '</span></div><span>' + fd(f.dt).replace(/ 20\d\d/, '') + ' to ' + fd(l.dt).replace(/ 20\d\d/, '') + '<br>' + c + ' of ' + ix.length + ' done</span>'));
    
    ix.forEach(i => {
      const d = days[i], type = typeOf(d), r = el('div', 'day' + (i === sel ? ' sel' : ''));
      const cb = el('input');
      cb.type = 'checkbox';
      cb.checked = !!done[d.iso];
      cb.setAttribute('aria-label', 'Done: ' + d.iso);
      cb.onchange = () => {
        if (cb.checked) done[d.iso] = 1;
        else delete done[d.iso];
        save();
        render();
      };
      
      const t = el('div', 'dt', DN[d.dt.getDay()].slice(0, 3) + ' ' + d.dt.getDate() + ' ' + d.dt.toLocaleDateString('en-GB', { month: 'short' }) + '<small>' + (type === 'Weekday' ? 'Work ' + d.ws.replace(':00', '') + ' to ' + d.we.replace(':00', '') : 'Off') + '</small>');
      t.onclick = () => {
        sel = i;
        render();
        scrollTo(0, 0);
      };
      
      const c2 = el('div', 0, '<p><em>Morning:</em> ' + d.m + '</p><p><em>Lunch:</em> ' + d.l + '</p><p><em>Evening:</em> ' + d.e + '</p>');
      r.append(cb, t, c2);
      de.appendChild(r);
    });
    w.appendChild(de);
  });
}

function stats() {
  const n = Object.keys(done).length;
  document.getElementById('pf').style.width = (n / days.length * 100) + '%';
  document.getElementById('pt').textContent = n + ' of ' + days.length + ' days done';
  document.getElementById('wk').textContent = Math.round(n / days.length * 100) + '% complete';
}

let tab = 'Weekday';

function tl() {
  const b = document.getElementById('ttb');
  b.innerHTML = '';
  ['Weekday', 'Saturday', 'Sunday'].forEach(k => {
    const x = el('button', 0, k === 'Weekday' ? 'Monday to Friday' : k);
    x.setAttribute('aria-pressed', k === tab);
    x.onclick = () => {
      tab = k;
      tl();
    };
    b.appendChild(x);
  });
  
  const l = document.getElementById('ttl');
  l.innerHTML = '';
  D.tt.filter(r => r[0] === tab).forEach(r => {
    const x = el('div', 'row', '<div>' + fm(r[1]) + ' to ' + fm(r[2]) + '</div><div>' + r[3] + ' <small>' + r[4] + '</small></div>');
    x.style.borderLeftColor = 'var(' + COL[r[4]] + ')';
    l.appendChild(x);
  });
}

function render() {
  hero();
  weeks();
  stats();
}

